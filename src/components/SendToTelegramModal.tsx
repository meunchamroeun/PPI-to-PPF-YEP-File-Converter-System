"use client";

import React, { useState, useEffect } from "react";
import {
  Send,
  FileCheck,
  CheckCircle2,
  AlertCircle,
  X,
  ExternalLink,
  Bot,
  RefreshCw,
  Key,
  MessageSquare,
  Share2,
  Download,
} from "lucide-react";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { useTranslation } from "@/lib/i18n/LanguageContext";

export interface SendToTelegramModalProps {
  isOpen: boolean;
  onClose: () => void;
  fileBlob?: Blob | null;
  filename?: string;
  defaultChatId?: string | number;
}

export const SendToTelegramModal: React.FC<SendToTelegramModalProps> = ({
  isOpen,
  onClose,
  fileBlob,
  filename = "Yamaha_Package.ppf",
  defaultChatId,
}) => {
  const { t, language } = useTranslation();
  const TELEGRAM_MAX_BYTES = 50 * 1024 * 1024; // 50 MB Telegram Bot API limit

  const [chatId, setChatId] = useState<string>("");
  const [botToken, setBotToken] = useState<string>("");
  const [showTokenInput, setShowTokenInput] = useState<boolean>(false);
  const [isSending, setIsSending] = useState<boolean>(false);
  const [statusMessage, setStatusMessage] = useState<{
    type: "success" | "error" | "info";
    text: string;
  } | null>(null);

  const fileSizeLabel = fileBlob
    ? fileBlob.size >= 1024 * 1024
      ? `${(fileBlob.size / 1024 / 1024).toFixed(1)} MB`
      : `${(fileBlob.size / 1024).toFixed(1)} KB`
    : "Ready";

  const fileTooLarge = !!fileBlob && fileBlob.size > TELEGRAM_MAX_BYTES;

  useEffect(() => {
    if (typeof window !== "undefined") {
      const savedChatId = localStorage.getItem("saved_tg_chat_id");
      if (defaultChatId) {
        setChatId(String(defaultChatId));
      } else if (savedChatId) {
        setChatId(savedChatId);
      }
    }
  }, [defaultChatId, isOpen]);

  if (!isOpen) return null;

  const handleDirectDownload = () => {
    if (!fileBlob) return;
    const url = URL.createObjectURL(fileBlob);
    const a = document.createElement("a");
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const handleSend = async () => {
    if (!chatId.trim()) {
      setStatusMessage({
        type: "error",
        text: language === "kh" ? "សូមបញ្ចូល Telegram Chat ID ឬ Username (@username)!" : "Please enter a Telegram Chat ID or Username (@username)!",
      });
      return;
    }

    if (!fileBlob) {
      setStatusMessage({
        type: "error",
        text: language === "kh" ? "រកមិនឃើញទិន្នន័យឯកសារដើម្បីផ្ញើឡើយ។" : "No file data available to send.",
      });
      return;
    }

    setIsSending(true);
    setStatusMessage(null);

    try {
      if (typeof window !== "undefined") {
        localStorage.setItem("saved_tg_chat_id", chatId.trim());
        // Note: bot token is intentionally NOT saved to localStorage for security
      }

      const formData = new FormData();
      formData.append("chatId", chatId.trim());
      formData.append("filename", filename);
      if (botToken.trim()) {
        formData.append("botToken", botToken.trim());
      }

      // If file exceeds Telegram limit (50 MB), do NOT send 148 MB over HTTP payload
      // Instead, send a notification receipt with file details to Telegram
      if (fileTooLarge) {
        formData.append("isNotificationOnly", "true");
        formData.append("fileSizeBytes", String(fileBlob.size));
      } else {
        formData.append("file", fileBlob, filename);
        formData.append(
          "caption",
          `Yamaha Converted Package: ${filename}\nFormat: ${filename.endsWith(".ppf") ? "Yamaha PPF (YEM Project)" : "Yamaha YEP"}\nGenerated by ExpVoice Studio`
        );
      }

      const res = await fetch("/api/telegram/send", {
        method: "POST",
        body: formData,
      });

      // Safely parse response text to avoid "Unexpected token 'R' in JSON"
      const rawText = await res.text();
      let data: any = {};
      try {
        data = JSON.parse(rawText);
      } catch {
        if (res.status === 413 || rawText.includes("Request Entity Too Large")) {
          throw new Error(
            language === "kh"
              ? "ឯកសារមានទំហំធំពេក (Request Entity Too Large) មិនអាចផ្ញើកាត់ Server បានទេ។ សូមប្រើប៊ូតុង 'ទាញយកឯកសារ PPF' ផ្ទាល់។"
              : "File is too large for web server transfer (413 Request Entity Too Large). Please use the Direct Download button."
          );
        }
        throw new Error(rawText || `Server error (${res.status})`);
      }

      if (res.ok && data.success) {
        setStatusMessage({
          type: "success",
          text:
            data.notice === "LARGE_FILE_NOTIFICATION"
              ? language === "kh"
                ? `បានផ្ញើព័ត៌មានលម្អិតនៃឯកសារទៅ Telegram រួចរាល់! សូមចុច "ទាញយកឯកសារ PPF" ដើម្បីរក្សាទុកក្នុងកុំព្យូទ័រ។`
                : `Pack details delivered to Telegram! Please use "Download Converted File" to save the file locally.`
              : language === "kh"
              ? `ឯកសារ "${filename}" ត្រូវបានផ្ញើទៅ Telegram ដោយជោគជ័យ!`
              : `File "${filename}" was successfully delivered to your Telegram chat!`,
        });
      } else {
        setStatusMessage({
          type: "error",
          text: data.message || data.error || (language === "kh" ? "ការផ្ញើបានបរាជ័យ។" : "Transfer failed."),
        });
      }
    } catch (err: any) {
      setStatusMessage({
        type: "error",
        text: err.message || (language === "kh" ? "មានបញ្ហាតភ្ជាប់ទៅ Telegram Server។" : "Network error contacting Telegram."),
      });
    } finally {
      setIsSending(false);
    }
  };

  return (
    <div className="fixed inset-0 z-50 bg-slate-950/80 backdrop-blur-md flex items-center justify-center p-4">
      <div
        className="relative w-full max-w-lg rounded-3xl border border-border shadow-2xl overflow-hidden animate-scale-in ring-1 ring-border/50 text-foreground"
        style={{ backgroundColor: "var(--card)" }}
      >
        {/* Modal Top Bar */}
        <div
          className="flex items-center justify-between px-6 py-4.5 border-b border-border"
          style={{ backgroundColor: "var(--card)" }}
        >
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-2xl bg-[#229ED9]/10 text-[#229ED9] flex items-center justify-center shrink-0 shadow-xs ring-1 ring-[#229ED9]/20">
              <Send className="w-5 h-5" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h3 className="font-bold text-sm text-foreground">
                  {language === "kh" ? "ផ្ញើឯកសារទៅកាន់ Telegram" : "Send File to Telegram"}
                </h3>
                <span className="text-[10px] font-mono font-semibold px-2 py-0.5 rounded-full text-[#229ED9] bg-[#229ED9]/10 border border-[#229ED9]/20">
                  BOT API
                </span>
              </div>
              <p className="text-[11px] text-muted-foreground mt-0.5">
                {language === "kh"
                  ? "ផ្ញើឯកសារដែលបាន Convert ទៅកាន់ Chat ឬ Bot របស់អ្នកផ្ទាល់"
                  : "Deliver converted file directly into your Telegram chat"}
              </p>
            </div>
          </div>
          <button
            type="button"
            onClick={onClose}
            className="p-2 rounded-xl text-muted-foreground hover:text-foreground hover:bg-muted transition"
            title={language === "kh" ? "បិទ" : "Close"}
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Modal Body */}
        <div className="p-6 space-y-4">
          {/* 50 MB Telegram limit warning */}
          {fileTooLarge && (
            <div className="p-3 rounded-xl text-xs flex items-start gap-2 bg-amber-500/10 border border-amber-500/20 text-amber-600 dark:text-amber-400">
              <AlertCircle className="w-4 h-4 shrink-0 mt-0.5" />
              <span className="flex-1 leading-relaxed">
                {language === "kh"
                  ? `ឯកសារ ${fileSizeLabel} លើសពីដែនកំណត់ 50 MB របស់ Telegram Bot API។ Telegram នឹងបដិសេធការផ្ញើ។ សូម Compress ឯកសារ ឬផ្ញើតាម Cloud Storage មុន។`
                  : `File is ${fileSizeLabel} — Telegram Bot API rejects documents over 50 MB. Please compress or share via cloud storage instead.`}
              </span>
            </div>
          )}

          {/* File Card Info */}
          <div className="p-3.5 rounded-2xl bg-muted/60 border border-border flex items-center justify-between">
            <div className="flex items-center gap-3 min-w-0">
              <div className="w-10 h-10 rounded-xl bg-emerald-500/10 text-emerald-600 dark:text-emerald-400 flex items-center justify-center shrink-0">
                <FileCheck className="w-5 h-5" />
              </div>
              <div className="min-w-0">
                <div className="font-bold text-xs text-foreground truncate">
                  {filename}
                </div>
                <div className="text-[10px] text-muted-foreground font-mono">
                  {fileSizeLabel}
                </div>
              </div>
            </div>
            <Badge variant="outline" className="font-mono text-[10px] uppercase border-emerald-500/30 text-emerald-600 dark:text-emerald-400 bg-emerald-500/5">
              {filename.split(".").pop() || "PPF"}
            </Badge>
          </div>

          {/* Form: Chat ID / Username */}
          <div className="space-y-1.5">
            <label className="text-xs font-semibold text-foreground flex items-center gap-1.5">
              <MessageSquare className="w-3.5 h-3.5 text-[#229ED9]" />
              <span>{language === "kh" ? "Telegram Chat ID ឬ Username:" : "Telegram Chat ID or Username:"}</span>
            </label>
            <input
              type="text"
              placeholder={language === "kh" ? "ឧ. @username ឬ 123456789" : "e.g. @your_username or 123456789"}
              value={chatId}
              onChange={(e) => setChatId(e.target.value)}
              className="w-full px-3.5 py-2.5 rounded-xl bg-background border border-border text-xs text-foreground placeholder:text-muted-foreground focus:outline-none focus:ring-2 focus:ring-[#229ED9]/20 focus:border-[#229ED9] transition"
            />
            <p className="text-[10px] text-muted-foreground leading-relaxed">
              {language === "kh"
                ? "ចំណាំ៖ សូមចុច /start ជាមួយ Bot ជាមុនសិន ដើម្បីឱ្យ Bot មានសិទ្ធិផ្ញើសារជូនលោកអ្នក។"
                : "Note: You must click /start on the bot first so it has permission to message you."}
            </p>
          </div>

          {/* Custom Bot Token Toggle */}
          <div className="pt-0.5">
            <button
              type="button"
              onClick={() => setShowTokenInput(!showTokenInput)}
              className="text-[11px] font-semibold text-[#229ED9] hover:text-[#1E8BC0] flex items-center gap-1.5 transition"
            >
              <Key className="w-3 h-3" />
              <span>
                {showTokenInput
                  ? language === "kh"
                    ? "លាក់ការកំណត់ Bot Token"
                    : "Hide Custom Bot Token"
                  : language === "kh"
                  ? "កំណត់ Bot Token ផ្ទាល់ខ្លួន (ពី @BotFather)"
                  : "Set Custom Bot Token (from @BotFather)"}
              </span>
            </button>

            {showTokenInput && (
              <div className="mt-2 space-y-1.5 p-3 rounded-xl bg-muted/50 border border-border">
                <label className="text-[11px] font-semibold text-foreground flex items-center gap-1.5">
                  <Bot className="w-3.5 h-3.5 text-[#229ED9]" />
                  <span>Bot Token:</span>
                </label>
                <input
                  type="password"
                  placeholder="123456789:ABCdefGHIjklMNOpqrsTUVwxyz"
                  value={botToken}
                  onChange={(e) => setBotToken(e.target.value)}
                  className="w-full px-3 py-2 rounded-lg bg-background border border-border text-xs font-mono text-foreground placeholder:text-muted-foreground focus:outline-none focus:ring-2 focus:ring-[#229ED9]/20 focus:border-[#229ED9]"
                />
                <p className="text-[10px] text-muted-foreground">
                  {language === "kh"
                    ? "ទុកចោលដើម្បីប្រើប្រាស់ Bot លំនាំដើមរបស់ប្រព័ន្ធ (@PPI_PPF_ConvertBot)"
                    : "Leave blank to use default system bot (@PPI_PPF_ConvertBot)"}
                </p>
              </div>
            )}
          </div>

          {/* Status Message */}
          {statusMessage && (
            <div
              className={`p-3 rounded-xl text-xs flex items-center gap-2 ${
                statusMessage.type === "success"
                  ? "bg-emerald-500/10 border border-emerald-500/20 text-emerald-600 dark:text-emerald-400"
                  : "bg-rose-500/10 border border-rose-500/20 text-rose-600 dark:text-rose-400"
              }`}
            >
              {statusMessage.type === "success" ? (
                <CheckCircle2 className="w-4 h-4 text-emerald-500 shrink-0" />
              ) : (
                <AlertCircle className="w-4 h-4 text-rose-500 shrink-0" />
              )}
              <span className="flex-1 text-[11px] leading-relaxed">{statusMessage.text}</span>
            </div>
          )}

          {/* Action Buttons */}
          <div className="space-y-2.5 pt-2">
            {/* Direct Download Button (especially useful when file exceeds 50 MB) */}
            {fileBlob && (
              <Button
                onClick={handleDirectDownload}
                type="button"
                variant="outline"
                className="w-full h-11 rounded-2xl border-emerald-500/30 bg-emerald-500/10 hover:bg-emerald-500/20 text-emerald-600 dark:text-emerald-400 text-xs font-bold flex items-center justify-center gap-2 transition active:scale-[0.98] cursor-pointer"
              >
                <Download className="w-4 h-4" />
                <span>
                  {language === "kh"
                    ? `ទាញយកឯកសារ ${filename.endsWith(".ppf") ? "PPF" : "YEP"} ផ្ទាល់ (${fileSizeLabel})`
                    : `Direct Download ${filename.endsWith(".ppf") ? "PPF" : "YEP"} (${fileSizeLabel})`}
                </span>
              </Button>
            )}

            <Button
              onClick={handleSend}
              disabled={isSending}
              className="w-full h-11 rounded-2xl bg-[#229ED9] hover:bg-[#1E8BC0] text-white text-xs font-bold flex items-center justify-center gap-2 shadow-md shadow-[#229ED9]/25 transition active:scale-[0.98] cursor-pointer"
            >
              {isSending ? (
                <>
                  <RefreshCw className="w-4 h-4 animate-spin" />
                  <span>{language === "kh" ? "កំពុងផ្ញើទៅ Telegram..." : "Sending to Telegram..."}</span>
                </>
              ) : (
                <>
                  <Send className="w-4 h-4" />
                  <span>
                    {fileTooLarge
                      ? language === "kh"
                        ? "ផ្ញើព័ត៌មានកញ្ចប់សំឡេងទៅ Telegram"
                        : "Send Pack Details to Telegram"
                      : language === "kh"
                      ? "ផ្ញើឯកសារទៅ Telegram ឥឡូវនេះ"
                      : "Send File to Telegram Now"}
                  </span>
                </>
              )}
            </Button>

            <div className="flex items-center gap-2 pt-1">
              <a
                href="https://t.me/PPI_PPF_ConvertBot"
                target="_blank"
                rel="noopener noreferrer"
                className="flex-1"
              >
                <Button
                  type="button"
                  variant="outline"
                  className="w-full h-9.5 rounded-xl border-border bg-muted/40 hover:bg-muted text-xs font-semibold flex items-center justify-center gap-1.5 transition text-foreground"
                >
                  <Bot className="w-3.5 h-3.5 text-[#229ED9]" />
                  <span>@PPI_PPF_ConvertBot</span>
                  <ExternalLink className="w-3 h-3 text-muted-foreground" />
                </Button>
              </a>

              <Button
                type="button"
                variant="secondary"
                onClick={onClose}
                className="h-9.5 px-5 rounded-xl bg-muted/70 hover:bg-muted text-xs font-semibold text-foreground border border-border/60 transition"
              >
                {language === "kh" ? "បិទ" : "Close"}
              </Button>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
